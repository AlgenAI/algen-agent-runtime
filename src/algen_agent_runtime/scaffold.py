async def run(question: str) -> str:
    """Execute the {slug} agent with the given question."""
    config_path = Path(__file__).with_name("agent.yaml")
    settings = load_settings((config_path,))
    container = build_container(settings)
    try:
        client = AlgenAgentRuntimeClient(container.runtime)
        result = await client.run(
            RunRequest(
                agent="{slug}",
                input=question,
                tenant_id="default-tenant",
                user_id="default-user",
            )
        )
        if result.error:
            raise RuntimeError(result.error)
        return result.output or ""
    finally:
        container.close()


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Run {slug}")
    parser.add_argument("question", nargs="?", default="Hello, what can you do?")
    args = parser.parse_args(argv)
    output = asyncio.run(run(args.question))
    print(output)


if __name__ == "__main__":
    main()
