TemplateName = Literal["agent", "approval", "workflow"]
AVAILABLE_TEMPLATES: tuple[TemplateName, ...] = ("agent", "approval", "workflow")


def _sanitize_name(name: str) -> tuple[str, str]:
    """Return (slug, python_identifier) from user project name."""
    cleaned = re.sub(r"[^\w\-]", "", name).strip("_-")
    if not cleaned:
        raise ValueError(f"Invalid project name {name!r}: must contain alphanumeric characters")
    slug = cleaned.lower().replace("_", "-")
    ident = cleaned.lower().replace("-", "_")
    if not ident[0].isalpha():
        ident = f"agent_{ident}"
    return slug, ident


