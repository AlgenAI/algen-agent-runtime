def scaffold_project(
    name: str,
    target_dir: str | Path,
    template: TemplateName = "agent",
    *,
    force: bool = False,
) -> Path:
    """Scaffold a new Algen Agent Runtime project deterministically."""
    if template not in AVAILABLE_TEMPLATES:
        raise ValueError(
            f"Unknown template {template!r}; available templates: {', '.join(AVAILABLE_TEMPLATES)}"
        )

    slug, ident = _sanitize_name(name)
    dest = Path(target_dir).resolve()

    if dest.exists() and any(dest.iterdir()) and not force:
        raise FileExistsError(
            f"Target directory {dest} already exists and is not empty. Use --force to overwrite."
        )

    dest.mkdir(parents=True, exist_ok=True)

    if template == "agent":
        files = _agent_template(slug, ident)
    elif template == "approval":
        files = _approval_template(slug, ident)
    elif template == "workflow":
        files = _workflow_template(slug, ident)
    else:
        raise ValueError(f"Unsupported template {template}")

    for filename, content in files.items():
        file_path = dest / filename
        file_path.write_text(content, encoding="utf-8")

    return dest
